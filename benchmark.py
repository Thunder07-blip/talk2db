import os
import sys
import time
import json
from pathlib import Path
from dataclasses import dataclass

@dataclass
class BenchmarkResult:
    total: int = 0
    passed: int = 0
    failed: int = 0
    avg_latency_ms: float = 0.0

def run_benchmark(db_path: Path, questions_file: Path) -> BenchmarkResult:
    print(f"\\n{'='*50}")
    print(f"BENCHMARK RUN: {db_path.name}")
    print(f"{'='*50}")
    
    # Set the environment variable BEFORE importing app modules
    os.environ["TALK2DB_DB_PATH"] = str(db_path.absolute())
    
    # Now import app modules so they pick up the new env var
    from app.llm.pipeline import ask
    from app.schema import extract_schema
    from app.config import DATABASE_PATH
    
    # Extract schema once for the benchmark
    print("Extracting schema...")
    schema = extract_schema()
    print(f"Found {len(schema.tables)} tables.")
    
    with open(questions_file, 'r') as f:
        data = json.load(f)
        
    results = BenchmarkResult(total=len(data))
    total_time = 0
    
    for i, item in enumerate(data, 1):
        question = item['question']
        print(f"\\n[Q{i}/{results.total}] {question}")
        
        start = time.perf_counter()
        res = ask(question, schema=schema)
        latency = (time.perf_counter() - start) * 1000
        
        total_time += latency
        
        if res.success:
            print(f"  ✅ SUCCESS ({latency:.0f}ms)")
            print(f"  SQL: {res.generated_sql}")
            results.passed += 1
        else:
            print(f"  ❌ FAILED ({latency:.0f}ms)")
            print(f"  ERROR: {res.error}")
            results.failed += 1
            
    if results.total > 0:
        results.avg_latency_ms = total_time / results.total
        
    print(f"\\n{'='*50}")
    print(f"BENCHMARK COMPLETE")
    print(f"Passed: {results.passed}/{results.total} ({(results.passed/results.total)*100:.1f}%)")
    print(f"Avg Latency: {results.avg_latency_ms:.0f}ms")
    print(f"{'='*50}\\n")
    
    return results

if __name__ == "__main__":
    # Create a small benchmark file for Chinook
    benchmark_file = Path("chinook_benchmark.json")
    if not benchmark_file.exists():
        with open(benchmark_file, "w") as f:
            json.dump([
                {"question": "How many tracks are there in total?"},
                {"question": "What is the name of the album with ID 5?"},
                {"question": "List the top 3 countries by number of customers."},
                {"question": "What is the total revenue generated by invoice?"},
                {"question": "Find the names of all employees who report to employee 1."}
            ], f, indent=2)
            
    run_benchmark(DATABASE_PATH, benchmark_file)
